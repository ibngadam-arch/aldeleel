// دالة تهيئة الجامعات في المكون الفرعي
function initUniversities() {
    const select = document.getElementById('univSelect');
    if(!select) return;
    select.innerHTML = '<option value="">كل الجامعات</option>';
    const universities = [...new Set(admissionData.map(item => item.univ))];
    
    universities.forEach(univ => {
        const option = document.createElement('option');
        option.value = univ;
        option.textContent = univ;
        select.appendChild(option);
    });
}

// دالة البحث والفلترة حسب النسبة واسم الجامعة والكلية
function filterData() {
    const scoreInput = document.getElementById('scoreInput');
    const univSelect = document.getElementById('univSelect');
    const textSearch = document.getElementById('textSearch');
    const container = document.getElementById('resultsContainer');

    if(!container) return;

    const userScore = parseFloat(scoreInput ? scoreInput.value : 0) || 0;
    const selectedUniv = univSelect ? univSelect.value : "";
    const searchText = textSearch ? textSearch.value.trim().toLowerCase() : "";

    container.innerHTML = '';

    let filtered = admissionData.filter(item => {
        const matchesUniv = selectedUniv === "" || item.univ === selectedUniv;
        const matchesText = searchText === "" || 
                            item.college.toLowerCase().includes(searchText) || 
                            item.univ.toLowerCase().includes(searchText);
        return matchesUniv && matchesText;
    });

    // الترتيب الأبجدي أو حسب أعلى نسبة قبور
    filtered.sort((a, b) => b.rate - a.rate);

    const countElement = document.getElementById('resultsCount');
    if (countElement) {
        countElement.textContent = `النتائج المعروضة: ${filtered.length}`;
    }

    if (filtered.length === 0) {
        container.innerHTML = '<div class="no-results">لم يتم العثور على نتائج تطابق معايير البحث.</div>';
        return;
    }

    filtered.forEach(item => {
        const card = document.createElement('div');
        card.className = 'card';

        const isEligible = userScore > 0 && userScore >= item.rate;
        let badgeHtml = '';

        if (userScore > 0) {
            if (isEligible) {
                badgeHtml = '<span class="card-badge badge-eligible">متاح لنسبتك ✓</span>';
            } else {
                badgeHtml = `<span class="card-badge badge-not-eligible">يحتاج +${(item.rate - userScore).toFixed(1)}%</span>`;
            }
        }

        card.innerHTML = `
            ${badgeHtml}
            <div>
                <div class="card-university">${item.univ}</div>
                <div class="card-college">${item.college}</div>
            </div>
            <div class="card-details">
                <div class="detail-item">
                    <span class="label">حد القبول (النسبة)</span>
                    <span class="val">${item.rate}%</span>
                </div>
                <div class="detail-item">
                    <span class="label">المفاضلة</span>
                    <span class="val">${item.diff > 0 ? item.diff : 'غير محدد'}</span>
                </div>
            </div>
        `;
        container.appendChild(card);
    });
}

